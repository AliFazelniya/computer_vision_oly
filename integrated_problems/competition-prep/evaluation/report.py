def summarize_table(df, group_cols, value_cols, how="mean"):
    "Group a results DataFrame and aggregate. Returns a rounded DataFrame ready to print or paste into a report."
    return df.groupby(group_cols)[value_cols].agg(how).round(3)


def save_report(df, path, title="results"):
    "Write results to CSV and a human-readable Markdown file side by side. Returns the two paths."
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path.with_suffix(".csv"), index=False)
    md = f"# {title}\n\nrows: {len(df)}\n\n" + df.round(3).to_markdown(index=False) if hasattr(df, "to_markdown") else f"# {title}\n\n" + df.round(3).to_string(index=False)
    path.with_suffix(".md").write_text(md, encoding="utf-8")
    return path.with_suffix(".csv"), path.with_suffix(".md")


