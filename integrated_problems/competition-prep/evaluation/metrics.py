ANG_TOL, DIST_TOL = 3.0, 9.0


def score_wall(pred, gt_p1, gt_p2):
    """angle error (deg, mod 180) and distance error (px) of a predicted line against the truth."""
    if pred is None:
        return dict(angle_err=np.nan, dist_err=np.nan, detected=False, success=False)
    ang = angle_diff_deg(line_angle_deg(pred["p1"], pred["p2"]), line_angle_deg(gt_p1, gt_p2))
    mid = ((gt_p1[0] + gt_p2[0]) / 2, (gt_p1[1] + gt_p2[1]) / 2)
    dist = point_line_distance(mid, pred["p1"], pred["p2"])
    return dict(angle_err=ang, dist_err=dist, detected=True, success=bool(ang <= ANG_TOL and dist <= DIST_TOL))

def mot_eval(gt_frames, tr_frames, iou_thr=0.5):
    """CLEAR-MOT style evaluation. Frames are dicts {id: box_xyxy}. Returns counts plus missed / false TRACK counts."""
    n_gt = tp = fp = fn = idsw = 0; last = {}
    gt_present, gt_hit, tr_present, tr_hit = Counter(), Counter(), Counter(), Counter()
    for gt, hy in zip(gt_frames, tr_frames):
        matches = {}
        for g, gb in gt.items():                                                  # keep previous correspondences if still valid
            h = last.get(g)
            if h in hy and box_iou(gb, hy[h]) >= iou_thr: matches[g] = h
        rg = [g for g in gt if g not in matches]; rh = [h for h in hy if h not in matches.values()]
        if rg and rh:
            M = iou_matrix([gt[g] for g in rg], [hy[h] for h in rh])
            for i, j in zip(*linear_sum_assignment(-M)):
                if M[i, j] >= iou_thr: matches[rg[i]] = rh[j]
        for g in gt: gt_present[g] += 1
        for h in hy: tr_present[h] += 1
        for g, h in matches.items():
            if g in last and last[g] != h: idsw += 1
            last[g] = h; gt_hit[g] += 1; tr_hit[h] += 1
        tp += len(matches); fn += len(gt) - len(matches); fp += len(hy) - len(matches); n_gt += len(gt)
    missed = sum(1 for g in gt_present if gt_hit[g] / gt_present[g] < 0.2)
    false_tr = sum(1 for h in tr_present if tr_present[h] >= 3 and tr_hit[h] / tr_present[h] < 0.2)
    return dict(n_gt=n_gt, TP=tp, FN=fn, FP=fp, IDSW=idsw, missed_tracks=missed, false_tracks=false_tr, MOTA=1.0 - (fn + fp + idsw) / max(n_gt, 1))

def evaluate_detection(det_fn, scenes, iou_thr=0.5):
    tp = fp = fn = 0; ious = []; rows = []
    for img, regs in scenes:
        dets = det_fn(img); gt = [r["box"] for r in regs]
        M = iou_matrix(gt, [b for b, _ in dets]) if dets else np.zeros((len(gt), 0)); used = set(); m = 0
        for gi in np.argsort(-M.max(1)) if M.size else []:
            j = int(np.argmax(M[gi]));
            if M[gi, j] >= iou_thr and j not in used: used.add(j); m += 1; ious.append(M[gi, j])
        tp += m; fn += len(gt) - m; fp += len(dets) - m
    p, r = tp / max(tp + fp, 1), tp / max(tp + fn, 1)
    return dict(scenes=len(scenes), gt_regions=tp + fn, tp=tp, fp=fp, fn=fn, precision=p, recall=r, f1=2 * p * r / max(p + r, 1e-9), mean_iou=float(np.mean(ious)) if ious else 0.0)


