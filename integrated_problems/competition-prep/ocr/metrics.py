import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))     # lets modules import their siblings when run as scripts
from ocr.normalize import normalize_eval


def edit_distance(a, b):
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1): cur.append(min(prev[j - 1] + (ca != cb), prev[j] + 1, cur[j - 1] + 1))
        prev = cur
    return prev[-1]

def cer(ref, hyp, normalize=True):
    """Character error rate on the canonical form (newlines count as spaces)."""
    r, h = (normalize_eval(ref), normalize_eval(hyp)) if normalize else (ref, hyp)
    return edit_distance(r, h) / max(len(r), 1)


def _selftest():
    assert edit_distance("kitten", "sitting") == 3 and edit_distance("", "abc") == 3 and edit_distance("abc", "") == 3 and edit_distance("x", "x") == 0
    assert cer("سلام", "سلام") == 0.0 and cer("سلام", "سلم") == 0.25 and cer("می\u200cکنند", "می کنند") == 0.0       # ZWNJ == space after canonicalisation
    assert cer("کتاب", "", normalize=False) == 1.0 and cer("", "", normalize=False) == 0.0


