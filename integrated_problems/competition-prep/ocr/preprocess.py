import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))     # lets modules import their siblings when run as scripts
import cv2
import numpy as np


def dynamic_range(g):
    """Robust contrast measure. NOT p98-p2: text ink is only a few % of the pixels, so p2 would just be the background."""
    return float(np.percentile(g, 99.5) - np.percentile(g, 0.5))

def sharpness_ratio(g):
    """Peak edge gradient divided by contrast (units: 1/pixel). For a Gaussian-blurred step edge this is ~0.4/sigma."""
    f = g.astype(np.float32); gx, gy = cv2.Sobel(f, cv2.CV_32F, 1, 0, ksize=3) / 8.0, cv2.Sobel(f, cv2.CV_32F, 0, 1, ksize=3) / 8.0
    return float(np.percentile(np.hypot(gx, gy), 99.7) / max(dynamic_range(g), 1.0))

def estimate_skew(gray, max_angle=25.0, min_gain=1.15):
    """Projection-profile skew search. Returns 0.0 unless the best angle makes the row profile clearly SHARPER than no rotation (safeguard)."""
    g = cv2.medianBlur(gray if gray.shape[1] <= 700 else cv2.resize(gray, None, fx=700 / gray.shape[1], fy=700 / gray.shape[1]), 3)
    _, ink = cv2.threshold(g, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)
    if (ink > 0).mean() > 0.5: ink = 255 - ink
    h, w = ink.shape
    def score(a):
        prof = cv2.warpAffine(ink, cv2.getRotationMatrix2D((w / 2, h / 2), a, 1.0), (w, h), flags=cv2.INTER_NEAREST).sum(1).astype(np.float64)
        return float(np.sum(np.diff(prof) ** 2))
    coarse = max(np.arange(-max_angle, max_angle + 1e-9, 1.0), key=score)
    best = float(max(np.arange(coarse - 1, coarse + 1 + 1e-9, 0.25), key=score))
    return best if score(best) >= min_gain * max(score(0.0), 1.0) else 0.0

def text_band_height(gray):
    _, ink = cv2.threshold(cv2.medianBlur(gray, 3), 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)
    if (ink > 0).mean() > 0.5: ink = 255 - ink
    rows = (ink > 0).sum(1) > 0.01 * ink.shape[1]; b = np.concatenate([[0], rows.astype(np.int8), [0]]); d = np.diff(b)
    runs = [e - s for s, e in zip(np.where(d == 1)[0], np.where(d == -1)[0]) if e - s >= 6]
    return float(np.median(runs)) if runs else float(gray.shape[0])

def preprocess_auto(gray, return_steps=False):
    steps, g = [], gray.copy()
    lo, hi = np.percentile(g, 0.5), np.percentile(g, 99.5)
    if hi - lo < 150:                                                                         # low dynamic range -> stretch
        g = np.clip((g.astype(np.float32) - lo) / max(hi - lo, 1) * 255, 0, 255).astype(np.uint8); steps.append("contrast")
    noise = float(np.mean(np.abs(g.astype(np.float32) - cv2.medianBlur(g, 3).astype(np.float32))))
    if noise > 4.0: g = cv2.medianBlur(g, 3); steps.append("median")                          # impulse-like noise
    ang = estimate_skew(g)
    if abs(ang) > 1.0:                                                                        # tilt -> deskew (only if clearly justified)
        h, w = g.shape; M = cv2.getRotationMatrix2D((w / 2, h / 2), ang, 1.0); c, s = abs(M[0, 0]), abs(M[0, 1])
        nw, nh = int(h * s + w * c), int(h * c + w * s); M[0, 2] += nw / 2 - w / 2; M[1, 2] += nh / 2 - h / 2
        g = cv2.warpAffine(g, M, (nw, nh), flags=cv2.INTER_CUBIC, borderMode=cv2.BORDER_CONSTANT, borderValue=int(np.median(g))); steps.append(f"deskew{ang:+.0f}")
    sr = sharpness_ratio(g)                                                                   # measured BEFORE any upscaling
    if sr < 0.30:                                                                             # blurry -> unsharp mask, stronger when blurrier
        amt = float(np.clip(1.2 * (0.30 / max(sr, 0.05) - 1.0), 0.0, 2.5))
        g = np.clip(cv2.addWeighted(g, 1.0 + amt, cv2.GaussianBlur(g, (0, 0), 2.0), -amt, 0), 0, 255).astype(np.uint8); steps.append(f"unsharp{amt:.1f}")
    hb = text_band_height(g)
    if hb < 24:                                                                               # small text -> upscale towards a 30 px band height
        f = float(np.clip(30.0 / hb, 1.0, 3.0)); g = cv2.resize(g, None, fx=f, fy=f, interpolation=cv2.INTER_CUBIC); steps.append(f"upscale{f:.1f}")
    g = cv2.copyMakeBorder(g, 12, 12, 12, 12, cv2.BORDER_CONSTANT, value=int(np.median(g)))
    return (g, steps) if return_steps else g


def _selftest():
    img = np.full((120, 420), 235, np.uint8); cv2.putText(img, "HELLO WORLD", (20, 80), cv2.FONT_HERSHEY_SIMPLEX, 2.0, 20, 3, cv2.LINE_AA)
    out, steps = preprocess_auto(img, return_steps=True)
    assert out.ndim == 2 and out.dtype == np.uint8 and steps == [], f"clean image must be left alone (control!): {steps}"          # the level-0 control
    low = np.clip(128 + (img.astype(np.float32) - 128) * 0.2, 0, 255).astype(np.uint8)
    assert "contrast" in preprocess_auto(low, return_steps=True)[1] and dynamic_range(low) < 150 <= dynamic_range(img)
    blur = cv2.GaussianBlur(img, (0, 0), 3.0); assert sharpness_ratio(blur) < 0.30 <= sharpness_ratio(img)
    M = cv2.getRotationMatrix2D((210, 60), 12, 1.0); tilted = cv2.warpAffine(img, M, (420, 120), borderValue=235)
    assert abs(estimate_skew(tilted)) > 5, "should detect a 12-degree tilt"


