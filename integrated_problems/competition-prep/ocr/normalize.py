    assert normalize_persian("می\u200cخواهم", zwnj="space") == "می خواهم" and normalize_persian("می\u200cخواهم", zwnj="remove") == "میخواهم"
    assert normalize_persian("  سلام \u200f  دنیا\t") == "سلام دنیا" and normalize_persian("سَلام") == "سلام" and normalize_persian("") == ""
    assert normalize_eval("كتاب‌ها ١٢٣") == "کتاب ها 123"
    for s in ["علي كتاب ١٢٣", "می\u200cخواهم  ", " \u200f"]: assert normalize_eval(normalize_eval(s)) == normalize_eval(s)         # idempotent


