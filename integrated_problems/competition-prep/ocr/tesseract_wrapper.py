import cv2
import numpy as np

try:
    import pytesseract
    pytesseract.get_tesseract_version(); HAS_TESS = "fas" in pytesseract.get_languages(config="")
except Exception:
    pytesseract, HAS_TESS = None, False


def ensure_dark_on_light(g):
    """Tesseract expects dark text on a light background. If Otsu says the DARK class is the majority, the text is the bright minority: invert."""
    if g is None or g.size == 0: return g
    _, b = cv2.threshold(g, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)
    if b is None: return g
    return 255 - g if (b == 0).mean() > 0.5 else g

def prepare_crop(crop, min_h=60, pad=12):
    """Generic crop preparation: grayscale, fix polarity (white-on-blue signs!), upscale to a minimum height, pad with the border colour."""
    if crop is None or crop.size == 0 or min(crop.shape[:2]) == 0: return crop
    g = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY) if crop.ndim == 3 else crop
    g = ensure_dark_on_light(g)
    if g.shape[0] < min_h: g = cv2.resize(g, None, fx=min_h / g.shape[0], fy=min_h / g.shape[0], interpolation=cv2.INTER_CUBIC)
    return cv2.copyMakeBorder(g, pad, pad, pad, pad, cv2.BORDER_CONSTANT, value=int(np.median(g)))

def safe_ocr(img, psm=7, lang="fas", extra="", timeout=15):
    """Crash-/hang-safe Tesseract: returns '' instead of raising."""
    if not HAS_TESS: return ""
    try: return pytesseract.image_to_string(img, lang=lang, config=f"--oem 1 --psm {psm} {extra}".strip(), timeout=timeout).strip()
    except Exception: return ""


def _selftest():
    light_on_dark = np.full((40, 100), 20, np.uint8); light_on_dark[10:30, 20:80] = 240
    assert ensure_dark_on_light(light_on_dark).mean() > 128                                                                   # inverted to dark-on-light
    dark_on_light = 255 - light_on_dark; assert (ensure_dark_on_light(dark_on_light) == dark_on_light).all()                   # left alone
    p = prepare_crop(np.full((20, 60, 3), 200, np.uint8)); assert p.ndim == 2 and p.shape[0] >= 60
    out = safe_ocr(np.full((50, 200), 255, np.uint8)); assert isinstance(out, str)                                           # never raises
    print("Tesseract+fas available:", HAS_TESS)


