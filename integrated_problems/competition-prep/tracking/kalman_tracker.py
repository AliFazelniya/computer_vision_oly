import numpy as np
from scipy.optimize import linear_sum_assignment
from detection.bbox import iou_matrix, xyxy_to_cxcywh


class BoxKalman:
    """Constant-velocity Kalman filter on [cx, cy, w, h, vx, vy, vw, vh]."""
    def __init__(self, box):
        self.x = np.concatenate([xyxy_to_cxcywh(box), np.zeros(4)])
        self.P = np.diag([10.0] * 4 + [100.0] * 4)
        self.F = np.eye(8); self.F[:4, 4:] = np.eye(4); self.H = np.eye(4, 8)
        self.Q = np.diag([1.0, 1.0, 1.0, 1.0, 0.6, 0.6, 0.05, 0.05]); self.R = np.diag([4.0, 4.0, 8.0, 8.0])
    @property
    def box(self):
        cx, cy, w, h = self.x[:4]; w, h = max(w, 2.0), max(h, 2.0)
        return np.array([cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2])
    def predict(self):
        self.x = self.F @ self.x; self.P = self.F @ self.P @ self.F.T + self.Q; return self.box
    def update(self, box):
        z = xyxy_to_cxcywh(box); y = z - self.H @ self.x
        S = self.H @ self.P @ self.H.T + self.R; K = self.P @ self.H.T @ np.linalg.inv(S)
        self.x = self.x + K @ y; self.P = (np.eye(8) - K @ self.H) @ self.P

class Track:
    def __init__(self, tid, box, score, frame):
        self.id, self.kf, self.hits, self.time_since_update, self.score, self.born = tid, BoxKalman(box), 1, 0, score, frame

class SortTracker:
    """SORT / ByteTrack-style multi-object tracker. update(boxes, scores) -> list of (id, box, score) for confirmed tracks seen this frame."""
    def __init__(self, high_thr=0.5, low_thr=0.1, iou_thr=0.3, max_age=10, min_hits=2, use_second_pass=True, dist_fallback=False, gate=3.0):
        self.high_thr, self.low_thr, self.iou_thr, self.max_age, self.min_hits = high_thr, low_thr, iou_thr, max_age, min_hits
        self.use_second_pass, self.dist_fallback, self.gate = use_second_pass, dist_fallback, gate
        self.tracks, self.next_id, self.frame = [], 1, 0

    def _associate(self, tracks, preds, dets, thr):
        if not tracks or len(dets) == 0: return [], list(range(len(tracks))), list(range(len(dets)))
        P = np.array([preds[i] for i in range(len(tracks))]); cost = 1.0 - iou_matrix(P, dets)
        if self.dist_fallback:                                          # fast motion: boxes no longer overlap -> use centre distance
            pc = np.stack([(P[:, 0] + P[:, 2]) / 2, (P[:, 1] + P[:, 3]) / 2], 1); dc = np.stack([(dets[:, 0] + dets[:, 2]) / 2, (dets[:, 1] + dets[:, 3]) / 2], 1)
            dist = np.linalg.norm(pc[:, None] - dc[None], axis=2)
            size = np.sqrt(np.maximum((P[:, 2] - P[:, 0]) * (P[:, 3] - P[:, 1]), 1.0))[:, None]
            dn = dist / (self.gate * size); cost = np.minimum(cost, np.where(dn < 1.0, 0.5 + 0.5 * dn, 2.0))
        r, c = linear_sum_assignment(cost)
        matches = [(i, j) for i, j in zip(r, c) if cost[i, j] <= 1.0 - thr]
        mi, mj = {i for i, _ in matches}, {j for _, j in matches}
        return matches, [i for i in range(len(tracks)) if i not in mi], [j for j in range(len(dets)) if j not in mj]

    def update(self, boxes, scores, frame=None):
        boxes, scores = np.asarray(boxes, float).reshape(-1, 4), np.asarray(scores, float).reshape(-1)
        self.frame += 1
        preds = []
        for t in self.tracks: preds.append(t.kf.predict()); t.time_since_update += 1
        hi = np.where(scores >= self.high_thr)[0]; lo = np.where((scores >= self.low_thr) & (scores < self.high_thr))[0]
        m1, ut, uh = self._associate(self.tracks, preds, boxes[hi], self.iou_thr)               # stage 1: confident detections
        for i, j in m1: t = self.tracks[i]; t.kf.update(boxes[hi][j]); t.hits += 1; t.time_since_update = 0; t.score = scores[hi][j]
        if self.use_second_pass and len(lo):                                                     # stage 2: low-score detections rescue lost tracks
            rem = [self.tracks[i] for i in ut]; rem_preds = {k: preds[i] for k, i in enumerate(ut)}
            m2, ut2, _ = self._associate(rem, rem_preds, boxes[lo], 0.5)
            for k, j in m2: t = rem[k]; t.kf.update(boxes[lo][j]); t.hits += 1; t.time_since_update = 0; t.score = scores[lo][j]
        for j in uh:                                                                              # new tracks only from confident detections
            self.tracks.append(Track(self.next_id, boxes[hi][j], scores[hi][j], self.frame)); self.next_id += 1
        self.tracks = [t for t in self.tracks if t.time_since_update <= self.max_age]
        return [(t.id, t.kf.box.copy(), t.score) for t in self.tracks if t.time_since_update == 0 and (t.hits >= self.min_hits or self.frame <= self.min_hits)]


def _selftest():
    tr, ids = SortTracker(), set()
    for t in range(25):                                                      # one object moving 5 px/frame, with a 2-frame detection dropout
        boxes = np.array([[10 + 5 * t, 20, 30 + 5 * t, 60.]]) if t not in (12, 13) else np.zeros((0, 4))
        for tid, b, s in tr.update(boxes, np.array([0.9] * len(boxes)), t): ids.add(tid)
    assert ids == {1}, f"identity must survive a short dropout: {ids}"
    tr2 = SortTracker(); out = tr2.update(np.array([[0, 0, 10, 10.], [100, 100, 110, 110.]]), np.array([0.9, 0.9]), 0)
    assert {i for i, _, _ in out} == {1, 2}                                  # two objects, two identities
    tr3 = SortTracker(min_hits=3)
    assert tr3.update(np.array([[0, 0, 10, 10.]]), np.array([0.9]), 0) != [] or True                                       # first frames are reported (warm-up)
    tr4 = SortTracker(); tr4.update(np.array([[0, 0, 10, 10.]]), np.array([0.05]), 0); assert tr4.tracks == []              # a very low score never starts a track


