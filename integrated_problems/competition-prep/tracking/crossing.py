import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))     # lets modules import their siblings when run as scripts
import math
import numpy as np
from geometry.lines import line_abc, signed_distance, segments_intersect


class LineCrossingCounter:
    """
    Counts objects crossing the finite segment p1->p2 (with hysteresis + per-ID state + spatio-temporal de-duplication).
    direction = +1 when an object goes from the negative side of the line to the positive side, -1 for the opposite.
    margin=0 and dedup=False reproduces the NAIVE "count every sign change" counter.
    """
    def __init__(self, p1, p2, margin=4.0, ref="center", dedup=True, dedup_frames=8, dedup_dist=15.0, extend=12.0):
        self.p1, self.p2, self.margin, self.ref = np.array(p1, float), np.array(p2, float), float(margin), ref
        self.abc = line_abc(p1, p2); self.dedup, self.dedup_frames, self.dedup_dist = dedup, dedup_frames, dedup_dist
        u = (self.p2 - self.p1) / np.linalg.norm(self.p2 - self.p1)
        self.e1, self.e2 = tuple(self.p1 - u * extend), tuple(self.p2 + u * extend)           # finite segment, extended by a tolerance
        self.state, self.events = {}, []

    def _point(self, box):
        x1, y1, x2, y2 = box
        return ((x1 + x2) / 2, (y1 + y2) / 2) if self.ref == "center" else ((x1 + x2) / 2, y2)    # "bottom": feet of a person / wheels of a car

    def _is_duplicate(self, ev):
        return any(e["direction"] == ev["direction"] and abs(e["frame"] - ev["frame"]) <= self.dedup_frames and e["id"] != ev["id"]
                   and math.hypot(e["pos"][0] - ev["pos"][0], e["pos"][1] - ev["pos"][1]) <= self.dedup_dist for e in self.events[-20:])

    def update(self, frame_idx, tracks):
        """tracks: iterable of (track_id, box_xyxy). Returns the NEW events of this frame."""
        new = []
        for tid, box in tracks:
            pt = self._point(box); sd = signed_distance(pt, self.abc)
            st = self.state.setdefault(tid, dict(side=0, anchor=None))
            if abs(sd) < self.margin:                                   # RULE 1: inside the dead band -> no decision (hysteresis)
                continue
            side = 1 if sd > 0 else -1
            if st["side"] == 0:                                         # first confirmed position of this ID: remember, never count
                st.update(side=side, anchor=pt); continue
            if side != st["side"]:                                      # RULE 3: only an OPPOSITE confirmed side can produce an event
                if segments_intersect(st["anchor"], pt, self.e1, self.e2):      # RULE 2: the path must cross the finite segment
                    ev = dict(frame=frame_idx, id=tid, direction=side, pos=pt)
                    if not (self.dedup and self._is_duplicate(ev)):     # RULE 4: spatio-temporal de-duplication across IDs
                        self.events.append(ev); new.append(ev)
                st.update(side=side, anchor=pt)
            else:
                st["anchor"] = pt
        return new

    @property
    def counts(self):
        return dict(pos=sum(e["direction"] == 1 for e in self.events), neg=sum(e["direction"] == -1 for e in self.events))

def evaluate_crossings(gt_events, pred_events, frame_tol=10, dist_tol=45.0):
    """One-to-one matching of predicted crossings to true ones (same direction, close in time and space).
    Also counts DOUBLE-COUNTED events: unmatched predictions that duplicate an already-matched true crossing."""
    used_g, used_p, matched = set(), set(), []
    for pi, p in enumerate(pred_events):
        best, bd = None, 1e9
        for gi, g in enumerate(gt_events):
            if gi in used_g or g["direction"] != p["direction"] or abs(g["frame"] - p["frame"]) > frame_tol: continue
            dd = math.hypot(g["pos"][0] - p["pos"][0], g["pos"][1] - p["pos"][1])
            if dd <= dist_tol and dd < bd: best, bd = gi, dd
        if best is not None: used_g.add(best); used_p.add(pi); matched.append((best, pi))
    tp = len(matched); fp = len(pred_events) - tp; fn = len(gt_events) - tp
    dup = 0
    for pi, p in enumerate(pred_events):
        if pi in used_p: continue
        if any(g["direction"] == p["direction"] and abs(g["frame"] - p["frame"]) <= frame_tol and math.hypot(g["pos"][0] - p["pos"][0], g["pos"][1] - p["pos"][1]) <= dist_tol for g in gt_events): dup += 1
    prec, rec = tp / max(tp + fp, 1), tp / max(tp + fn, 1)
    return dict(gt=len(gt_events), pred=len(pred_events), tp=tp, fp=fp, fn=fn, double_counted=dup, precision=prec, recall=rec,
                f1=2 * prec * rec / max(prec + rec, 1e-9), count_error=abs(len(pred_events) - len(gt_events)))


def _selftest():
    c = LineCrossingCounter((0, 50), (100, 50), margin=4)
    for t, y in enumerate(range(20, 81, 4)): c.update(t, [(1, [45, y - 5, 55, y + 5])])                                      # a real crossing, top -> bottom
    assert c.counts == {"pos": 1, "neg": 0} and len(c.events) == 1, c.events
    j = LineCrossingCounter((0, 50), (100, 50), margin=4)
    for t in range(40): j.update(t, [(2, [45, 50 + (2 if t % 2 else -2) - 5, 55, 50 + (2 if t % 2 else -2) + 5])])           # jitter INSIDE the dead band
    assert j.events == [], "jitter must not be counted"
    n = LineCrossingCounter((0, 50), (100, 50), margin=0, dedup=False)
    for t in range(40): n.update(t, [(2, [45, 50 + (3 if t % 2 else -3) - 5, 55, 50 + (3 if t % 2 else -3) + 5])])
    assert len(n.events) > 10, "the naive counter (no dead band) over-counts: this is the failure the margin prevents"
    miss = LineCrossingCounter((0, 50), (100, 50), margin=4)                                                                  # passes the EXTENSION of the segment only
    for t, y in enumerate(range(20, 81, 4)): miss.update(t, [(3, [195, y - 5, 205, y + 5])])
    assert miss.events == [], "a path that does not cross the finite segment is not a crossing"
    ev = [dict(frame=10, id=1, direction=1, pos=(50, 50))]
    assert evaluate_crossings(ev, ev)["f1"] == 1.0 and evaluate_crossings(ev, [])["fn"] == 1 and evaluate_crossings([], ev)["fp"] == 1


