import numpy as np


def box_iou(a, b):
    xA, yA, xB, yB = max(a[0], b[0]), max(a[1], b[1]), min(a[2], b[2]), min(a[3], b[3])
    inter = max(0.0, xB - xA) * max(0.0, yB - yA)
    u = (a[2] - a[0]) * (a[3] - a[1]) + (b[2] - b[0]) * (b[3] - b[1]) - inter
    return inter / u if u > 0 else 0.0

def iou_matrix(A, B):
    """Vectorised IoU between every box in A (n,4) and every box in B (m,4), xyxy."""
    A, B = np.asarray(A, float).reshape(-1, 4), np.asarray(B, float).reshape(-1, 4)
    if len(A) == 0 or len(B) == 0: return np.zeros((len(A), len(B)))
    x1 = np.maximum(A[:, None, 0], B[None, :, 0]); y1 = np.maximum(A[:, None, 1], B[None, :, 1])
    x2 = np.minimum(A[:, None, 2], B[None, :, 2]); y2 = np.minimum(A[:, None, 3], B[None, :, 3])
    inter = np.clip(x2 - x1, 0, None) * np.clip(y2 - y1, 0, None)
    area = lambda X: (X[:, 2] - X[:, 0]) * (X[:, 3] - X[:, 1])
    union = area(A)[:, None] + area(B)[None, :] - inter
    return np.where(union > 0, inter / np.maximum(union, 1e-9), 0.0)

def nms(boxes, scores, iou_thr=0.5):
    """Greedy non-maximum suppression. Returns the indices to keep, best first."""
    boxes, scores = np.asarray(boxes, float).reshape(-1, 4), np.asarray(scores, float)
    order, keep = list(np.argsort(-scores)), []
    while order:
        i = order.pop(0); keep.append(int(i))
        if order:
            ious = iou_matrix(boxes[i:i + 1], boxes[order])[0]
            order = [j for j, v in zip(order, ious) if v <= iou_thr]
    return keep

def xyxy_to_cxcywh(b):
    return np.array([(b[0] + b[2]) / 2, (b[1] + b[3]) / 2, b[2] - b[0], b[3] - b[1]], float)


