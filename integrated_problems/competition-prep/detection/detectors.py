class BlobDetector:
    """Saturated-colour blob detector for the synthetic scenes (stand-in for YOLO). Score ~ blob area relative to a typical object."""
    def __init__(self, sat_thr=90, min_area=45, ref_area=600.0):
        self.sat_thr, self.min_area, self.ref_area = sat_thr, min_area, ref_area
    def detect(self, frame):
        hsv = cv2.cvtColor(frame, cv2.COLOR_BGR2HSV)
        mask = ((hsv[..., 1] >= self.sat_thr) & (hsv[..., 2] >= 70)).astype(np.uint8) * 255
        mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))
        n, _, stats, _ = cv2.connectedComponentsWithStats(mask, connectivity=8)
        boxes, scores = [], []
        for i in range(1, n):
            x, y, w, h, a = stats[i]
            if a >= self.min_area:
                boxes.append([x, y, x + w, y + h]); scores.append(float(np.clip(a / self.ref_area, 0.15, 1.0)))
        return np.array(boxes, float).reshape(-1, 4), np.array(scores, float)

class YoloDetector:
    """Ultralytics YOLO behind the same interface. weights: 'yolo11n.pt' (or the YOLO26 weights from Phase 3). classes: COCO ids (0 = person)."""
    def __init__(self, weights="yolo11n.pt", classes=(0,), conf=0.25, imgsz=640, device=None):
        from ultralytics import YOLO                                   # imported lazily: the notebook runs without ultralytics
        self.model, self.classes, self.conf, self.imgsz, self.device = YOLO(weights), list(classes), conf, imgsz, device
    def detect(self, frame):
        r = self.model.predict(frame, classes=self.classes, conf=self.conf, imgsz=self.imgsz, device=self.device, verbose=False)[0]
        return r.boxes.xyxy.cpu().numpy().astype(float).reshape(-1, 4), r.boxes.conf.cpu().numpy().astype(float)


