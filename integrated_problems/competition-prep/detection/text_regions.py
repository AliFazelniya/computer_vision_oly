def detect_text_regions(img, close_kernel=(41, 33), min_w=50, min_h=18, min_density=0.10, max_frac=0.8):
    """Classical text-region detector. Returns a list of (box_xyxy, score)."""
    g = cv2.GaussianBlur(cv2.cvtColor(img, cv2.COLOR_BGR2GRAY), (3, 3), 0)
    grad = cv2.morphologyEx(g, cv2.MORPH_GRADIENT, np.ones((3, 3), np.uint8))
    _, bw = cv2.threshold(grad, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)
    closed = cv2.morphologyEx(bw, cv2.MORPH_CLOSE, cv2.getStructuringElement(cv2.MORPH_RECT, close_kernel))
    closed = cv2.morphologyEx(closed, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))
    cnts, _ = cv2.findContours(closed, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    H, W = g.shape; out = []
    for c in cnts:
        x, y, w, h = cv2.boundingRect(c)
        if w < min_w or h < min_h or w > max_frac * W or h > max_frac * H or not (1.2 <= w / h <= 12): continue
        dens = float(bw[y:y + h, x:x + w].mean() / 255.0)
        if dens >= min_density: out.append(([x, y, x + w, y + h], dens))
    keep = nms([b for b, _ in out], [s for _, s in out], 0.3) if out else []
    return [out[i] for i in keep]


