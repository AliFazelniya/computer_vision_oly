def safe_method(method, default):
    "Wrap a solution so an exception or None never loses an item: return `default(img)` instead (the always-submit rule)."
    def wrapped(img):
        try:
            out = method(img)
        except Exception:
            out = None
        return out if out is not None else default(img)
    return wrapped


def make_wall_contest(seed, n=20):
    "A fresh hidden set of mixed-stress wall scenes: returns (images, ground_truth_lines)."
    rng = np.random.default_rng(seed); imgs, gts = [], []
    for k in range(n):
        lv = {f: int(rng.integers(0, 4)) for f in ["shadow", "noise", "broken", "distract", "angle"]}
        img, gt = make_wall_scene(seed * 100 + k, levels=lv, style="unseen" if k % 2 else "dev")
        imgs.append(img); gts.append((gt["p1"], gt["p2"]))
    return imgs, gts


def run_wall_contest(method, seed=31337, n=20, name="submission"):
    "Score `method(img) -> dict(p1, p2) | None` exactly like the notebook harness. Returns a one-row DataFrame."
    imgs, gts = make_wall_contest(seed, n)
    default = lambda img: dict(p1=(0, img.shape[0] / 2), p2=(img.shape[1], img.shape[0] / 2))
    safe = safe_method(method, default); rows = []
    for img, (p1, p2) in zip(imgs, gts):
        with Timer() as t: pred = safe(img)
        rows.append(dict(**score_wall(pred, p1, p2), ms=t.ms))
    df = pd.DataFrame(rows)
    return pd.DataFrame([dict(name=name, n=len(df), success=df.success.mean(), median_angle_err=df.angle_err.median(),
                              median_dist_err=df.dist_err.median(), mean_ms=df.ms.mean())])


