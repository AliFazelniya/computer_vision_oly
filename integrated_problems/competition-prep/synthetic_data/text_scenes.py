def find_persian_fonts(font_dir="fonts"):
    """{family: path} of installed fonts that contain the Persian letters + digits we need. Drop extra .ttf files into ./fonts if too few."""
    from fontTools.ttLib import TTFont
    cands = []
    try:
        out = subprocess.run(["fc-list", ":lang=fa", "file", "family"], capture_output=True, text=True, timeout=20).stdout
        for line in out.splitlines():
            path, _, fam = line.partition(": "); cands.append((fam.split(",")[0].split(":")[0].strip(), path.strip()))
    except Exception: pass
    for p in list(Path(font_dir).glob("*.ttf")) + list(Path(font_dir).glob("*.otf")): cands.append((p.stem, str(p)))
    STYLE = ("bold", "italic", "black", "thin", "light", "oblique", "semi", "medium", "extra", "condensed")
    cands.sort(key=lambda t: (0 if "regular" in Path(t[1]).name.lower() else 1, sum(w in Path(t[1]).name.lower() for w in STYLE), t[1]))
    fonts = {}
    for fam, path in cands:
        if fam in fonts or not path.lower().endswith((".ttf", ".otf")): continue
        if any(x in fam.lower() for x in ("mono", "unifont", "nastaliq", "free", "kufi")): continue          # unsuitable for a general dataset
        try:
            cmap = TTFont(path, fontNumber=0, lazy=True).getBestCmap()
            if all(ord(c) in cmap for c in PERSIAN_PROBE): fonts[fam] = path
        except Exception: pass
    return fonts

def render_text_ink(text, font_path, px, pad=2):
    """Tight ink mask (255 = ink) of one line of Persian text, correctly shaped (RAQM, or arabic-reshaper + bidi as fallback)."""
    if HAS_RAQM:
        font = ImageFont.truetype(font_path, px, layout_engine=ImageFont.Layout.RAQM); kw = dict(direction="rtl", language="fa")
    else:
        import arabic_reshaper; from bidi.algorithm import get_display
        font = ImageFont.truetype(font_path, px); kw = {}; text = get_display(arabic_reshaper.reshape(text))
    W = int(font.getlength(text, **kw)) + 2 * pad + 10; H = int(px * 1.9) + 2 * pad
    im = Image.new("L", (W, H), 0); ImageDraw.Draw(im).text((pad, pad + int(px * 0.2)), text, font=font, fill=255, **kw)
    a = np.array(im); ys, xs = np.nonzero(a > 40)
    return a[max(0, ys.min() - pad): ys.max() + 1 + pad, max(0, xs.min() - pad): xs.max() + 1 + pad]

def paste_ink(img, ink, x, y, target_h, color):
    """Alpha-composite an ink mask (resized to target_h) onto img at (x, y); clipped to the image. Returns the right edge x."""
    s = target_h / ink.shape[0]; m = cv2.resize(ink, (max(1, int(ink.shape[1] * s)), int(target_h)), interpolation=cv2.INTER_AREA)
    H, W = img.shape[:2]; x2, y2 = min(x + m.shape[1], W), min(y + m.shape[0], H)
    if x2 <= x or y2 <= y: return x + m.shape[1]
    a = (m[:y2 - y, :x2 - x].astype(np.float32) / 255.0)[..., None]
    img[y:y2, x:x2] = (img[y:y2, x:x2] * (1 - a) + np.array(color, np.float32) * a).astype(np.uint8)
    return x + m.shape[1]

def render_plate(rng, font_path, height=72):
    W = int(height * 4.3); p = np.full((height, W, 3), 250, np.uint8)
    dd, L, ddd, rr = "".join(rng.choice(PLATE_DIGITS, 2)), str(rng.choice(PLATE_LETTERS)), "".join(rng.choice(PLATE_DIGITS, 3)), "".join(rng.choice(PLATE_DIGITS, 2))
    cv2.rectangle(p, (1, 1), (W - 2, height - 2), (20, 20, 20), 3)
    sw = int(W * 0.12); p[3:height - 3, 3:sw] = (170, 70, 20)
    cv2.putText(p, "IR", (6, height - 10), cv2.FONT_HERSHEY_SIMPLEX, height / 125.0, (255, 255, 255), 2, cv2.LINE_AA)
    h = int(height * 0.52); y = (height - h) // 2; x = sw + int(height * 0.14)
    for part in (dd, L, ddd): x = paste_ink(p, render_text_ink(part, font_path, 60), x, y, h, (20, 20, 20)) + int(height * 0.16)
    xd = x - int(height * 0.04); cv2.line(p, (xd, 6), (xd, height - 6), (20, 20, 20), 2); x = xd + int(height * 0.12)
    paste_ink(p, render_text_ink("ایران", font_path, 40), x, int(height * 0.08), int(height * 0.2), (20, 20, 20))
    paste_ink(p, render_text_ink(rr, font_path, 60), x, int(height * 0.38), int(height * 0.46), (20, 20, 20))
    return p, dd + L + ddd + rr

def render_text_panel(rng, font_path, kind):
    if kind == "sign":
        bg, fg = [((170, 80, 20), (255, 255, 255)), ((60, 120, 30), (255, 255, 255)), ((245, 245, 245), (30, 30, 30))][int(rng.integers(0, 3))]
        lines = [str(rng.choice(SIGN_PHRASES))]
    else:
        bg, fg = (245, 245, 240), (25, 25, 25)
        lines = [str(rng.choice(LABEL_NAMES)), "".join(rng.choice(PLATE_DIGITS, int(rng.integers(5, 7)))) + " تومان", "وزن " + "".join(rng.choice(PLATE_DIGITS, 3)) + " گرم"]
    inks = [render_text_ink(l, font_path, 56) for l in lines]; lh = int(rng.integers(26, 38))
    ws = [int(i.shape[1] * lh / i.shape[0]) for i in inks]; Wp = max(ws) + 2 * lh; Hp = len(inks) * (lh + lh // 2) + lh
    p = np.full((Hp, Wp, 3), bg, np.uint8); y = lh // 2 + lh // 4
    for ink, w in zip(inks, ws):
        paste_ink(p, ink, (Wp - w) // 2, y, lh, fg); y += lh + lh // 2
    cv2.rectangle(p, (0, 0), (Wp - 1, Hp - 1), tuple(int(c * 0.6) for c in bg), 2)
    return p, "\n".join(lines)

def make_text_scene(seed, kinds=("plate",), clutter=0, size=(420, 560), min_gap=45):
    """Scene with one text object per entry of `kinds` ('plate' | 'sign' | 'label'). Returns img, regions=[dict(box, kind, text)]."""
    rng = np.random.default_rng(seed); H, W = size
    g = np.linspace(rng.uniform(90, 160), rng.uniform(120, 200), W, dtype=np.float32)[None, :, None] + cv2.resize(rng.normal(0, 10, (H // 20 + 2, W // 20 + 2)).astype(np.float32), (W, H))[..., None]
    img = np.clip(g + rng.normal(0, 3, (H, W, 1)) + np.array([rng.uniform(-15, 15), rng.uniform(-15, 15), rng.uniform(-15, 15)]), 0, 255).astype(np.uint8)
    boxes, regions = [], []
    names = list(FONTS); panels = []
    for kind in kinds:
        font = FONTS[str(rng.choice(names))]
        panel, text = render_plate(rng, font, int(rng.integers(60, 84))) if kind == "plate" else render_text_panel(rng, font, kind)
        if panel.shape[1] > W - 20: panel = cv2.resize(panel, (W - 20, int(panel.shape[0] * (W - 20) / panel.shape[1])))
        panels.append((kind, panel, text))
    for kind, panel, text in sorted(panels, key=lambda t: -t[1].shape[0] * t[1].shape[1]):      # largest first: easier to fit everything
        ph, pw = panel.shape[:2]; placed = False
        for _ in range(2000):                                    # objects are at least `min_gap` px apart (an explicit assumption of the classical detector)
            x, y = int(rng.integers(8, max(9, W - pw - 8))), int(rng.integers(8, max(9, H - ph - 8)))
            if all(x > b[2] + min_gap or x + pw < b[0] - min_gap or y > b[3] + min_gap or y + ph < b[1] - min_gap for b in boxes): placed = True; break
        if not placed: continue                                  # cannot fit another object with the required gap: skip it (ground truth stays consistent)
        img[y:y + ph, x:x + pw] = panel; boxes.append([x, y, x + pw, y + ph]); regions.append(dict(box=[x, y, x + pw, y + ph], kind=kind, text=text))
    # clutter: decoy rectangles WITHOUT text, lines, circles
    for _ in range([0, 3, 7, 12][clutter]):
        t = int(rng.integers(0, 3)); col = tuple(int(c) for c in rng.integers(30, 230, 3)); x, y = int(rng.integers(0, W - 40)), int(rng.integers(0, H - 40)); w, h = int(rng.integers(30, 120)), int(rng.integers(20, 70))
        cand = [x, y, x + w, y + h]
        if any(not (cand[0] > b[2] + 4 or cand[2] < b[0] - 4 or cand[1] > b[3] + 4 or cand[3] < b[1] - 4) for b in boxes): continue
        if t == 0: cv2.rectangle(img, (x, y), (x + w, y + h), col, -1 if rng.random() < .5 else 2)
        elif t == 1: cv2.line(img, (x, y), (x + w, y + h), col, int(rng.integers(1, 4)), cv2.LINE_AA)
        else: cv2.circle(img, (x + 20, y + 20), int(rng.integers(8, 25)), col, -1 if rng.random() < .5 else 2)
    return img, regions

