"""Synthetic wall/floor scenes with a known edge and five stress factors.

AUTO-GENERATED by the Phase 5 notebook (Day 38) from the functions tested there.
Run this file directly to execute its self-test:   python synthetic_data/wall_scenes.py
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))     # lets modules import their siblings when run as scripts
import math
import cv2
import numpy as np
from geometry.lines import fold_angle, line_abc, clip_line_to_rect


def _pt(p): return (int(round(p[0])), int(round(p[1])))

def make_wall_scene(seed, size=(360, 480), levels=None, style="dev"):
    """
    Render a wall/floor scene with a known wall edge. Returns (BGR uint8 image, ground-truth dict).
    levels: dict with keys shadow, noise, broken, distract, angle in 0..3.   style: "dev" or "unseen" (different looks, for Day 33).
    """
    rng = np.random.default_rng(seed); H, W = size
    L = dict(shadow=0, noise=0, broken=0, distract=0, angle=0); L.update(levels or {})

    # --- the true edge: a point (cx, cy), a direction d and a normal n; "floor" is the +n side
    amax = [5, 15, 30, 55][L["angle"]]
    theta = float(rng.uniform(-amax, amax))
    if L["angle"] == 3 and rng.random() < 0.2:
        theta = float(rng.choice([-1, 1]) * rng.uniform(68, 88))                  # near-vertical wall corner
    cx, cy = W / 2 + rng.uniform(-0.12, 0.12) * W, H / 2 + rng.uniform(-0.12, 0.12) * H
    t = math.radians(theta); d = np.array([math.cos(t), math.sin(t)]); n = np.array([-math.sin(t), math.cos(t)])
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
    sd = (xx - cx) * n[0] + (yy - cy) * n[1]                                         # signed distance to the edge (px)

    # --- surface colours: wall and floor differ in brightness AND in tint (albedo)
    if style == "unseen":
        base = rng.uniform(100, 235); drop = rng.choice([-1, 1]) * rng.uniform(25, 75); tint = rng.uniform(-25, 25, 3); shift = rng.uniform(5, 28, 3) * rng.choice([-1, 1], 3)
    else:
        base = rng.uniform(150, 215); drop = rng.choice([-1, 1]) * rng.uniform(30, 65); tint = rng.uniform(-10, 10, 3); shift = rng.uniform(6, 22, 3) * rng.choice([-1, 1], 3)
    wall = np.clip(base + tint, 0, 255); floor = np.clip(base - drop + tint + shift, 0, 255)
    alpha = np.clip(sd / 1.6 + 0.5, 0, 1)[..., None]                                 # anti-aliased 0 = wall, 1 = floor
    img = wall * (1 - alpha) + floor * alpha
    tex = cv2.resize(rng.normal(0, 1, (H // 24 + 2, W // 24 + 2)).astype(np.float32), (W, H), interpolation=cv2.INTER_CUBIC)
    img = np.clip(img + (tex * 4)[..., None], 0, 255)

    # --- broken edges: "objects" painted over the edge (rotated rectangles aligned with the edge)
    nb = [0, 1, 3, 5][L["broken"]]
    span = math.hypot(W, H)
    for _ in range(nb):
        s0 = rng.uniform(-0.35, 0.35) * span; glen = rng.uniform(0.07, 0.18) * span; hw = rng.uniform(18, 30)
        c0 = np.array([cx, cy]) + d * s0
        pts = np.array([c0 - d * glen / 2 - n * hw, c0 + d * glen / 2 - n * hw, c0 + d * glen / 2 + n * hw, c0 - d * glen / 2 + n * hw])
        col = 0.5 * (wall + floor) + rng.normal(0, 18, 3)
        layer = np.zeros((H, W), np.uint8); cv2.fillConvexPoly(layer, pts.astype(np.int32), 255)
        m = (cv2.GaussianBlur(layer, (0, 0), 0.8).astype(np.float32) / 255)[..., None]
        img = img * (1 - m) + (col + rng.normal(0, 6, (H, W, 3))) * m
    img = np.clip(img, 0, 255).astype(np.uint8)

    # --- distractor lines
    nd = L["distract"]
    def blend_line(p, q, col, thick, a):
        lay = img.copy(); cv2.line(lay, _pt(p), _pt(q), col, thick, cv2.LINE_AA)
        return cv2.addWeighted(lay, a, img, 1 - a, 0)
    if nd >= 1:                                                                      # tile grout on the floor
        sp = rng.uniform(45, 90); grout = np.zeros((H, W), np.uint8)
        for k in range(1, 12):
            p = np.array([cx, cy]) + n * k * sp; cv2.line(grout, _pt(p - d * 1500), _pt(p + d * 1500), 255, 1, cv2.LINE_AA)
        for k in range(-10, 11):
            p = np.array([cx, cy]) + d * k * sp * 1.4; cv2.line(grout, _pt(p), _pt(p + n * 1500), 255, 1, cv2.LINE_AA)
        img = (img * (1 - 0.2 * (grout / 255.0 * (sd > 3))[..., None])).astype(np.uint8)
    for _ in range([0, 1, 2, 4][nd]):                                                # picture frames on the wall
        for _try in range(10):
            fc = rng.uniform([40, 40], [W - 40, H - 40]); fw, fh = rng.uniform(40, 110), rng.uniform(35, 90)
            if ((fc - np.array([cx, cy])) @ n) < -(max(fw, fh) / 2 + 25):
                col = tuple(int(v) for v in rng.integers(20, 90, 3)) if rng.random() < .6 else tuple(int(v) for v in rng.integers(200, 250, 3))
                x1, y1, x2, y2 = fc[0] - fw / 2, fc[1] - fh / 2, fc[0] + fw / 2, fc[1] + fh / 2
                lay = img.copy(); cv2.rectangle(lay, _pt((x1, y1)), _pt((x2, y2)), col, int(rng.integers(2, 4)), cv2.LINE_AA)
                img = cv2.addWeighted(lay, 0.85, img, 0.15, 0); break
    if nd >= 2:                                                                      # decoy lines parallel to the real edge
        for _ in range([0, 0, 1, 3][nd]):
            off = rng.choice([-1, 1]) * rng.uniform(30, 85); ang = rng.uniform(-1.0, 1.0)
            dd = np.array([math.cos(t + math.radians(ang)), math.sin(t + math.radians(ang))]); p = np.array([cx, cy]) + n * off
            img = blend_line(p - dd * 1500, p + dd * 1500, (30, 30, 30) if rng.random() < .5 else (235, 235, 235), int(rng.integers(1, 3)), 0.55)
    for _ in range([0, 0, 2, 5][nd]):                                                # cables / random straight lines crossing the scene
        p = rng.uniform([0, 0], [W, H]); a = rng.uniform(0, math.pi); dd = np.array([math.cos(a), math.sin(a)])
        img = blend_line(p - dd * 900, p + dd * 900, (25, 25, 25) if rng.random() < .5 else (240, 240, 240), int(rng.integers(1, 3)), 0.6)
    if style == "unseen":                                                            # new distractor types never seen in development
        lay = np.zeros((H, W), np.uint8); a0 = rng.uniform(0, math.pi); dd = np.array([math.cos(a0), math.sin(a0)]); q = rng.uniform([0, 0], [W, H])
        cv2.line(lay, _pt(q - dd * 900), _pt(q + dd * 900), 255, int(rng.integers(14, 30)), cv2.LINE_AA)
        beam = (cv2.GaussianBlur(lay, (0, 0), 6).astype(np.float32) / 255 * rng.uniform(0.12, 0.28))[..., None]            # window light beam
        img = np.clip(img.astype(np.float32) * (1 + beam), 0, 255).astype(np.uint8)

    # --- shadows: multiplicative, same chromaticity (they darken, they don't recolour)
    shade = np.ones((H, W), np.float32)
    ns, blur, strength = [(0, 0, 0), (1, 40, 0.12), (1, 4.5, rng.uniform(0.3, 0.42)), (2, 2.0, rng.uniform(0.4, 0.55))][L["shadow"]]
    for _ in range(ns):
        c = np.array([cx, cy]) + rng.uniform(-110, 110, 2); r = rng.uniform(130, 260); a0 = rng.uniform(0, 2 * math.pi)
        poly = np.array([c + r * np.array([math.cos(a0 + k * 2.1 + rng.uniform(-.5, .5)), math.sin(a0 + k * 2.1 + rng.uniform(-.5, .5))]) for k in range(3)])
        layer = np.zeros((H, W), np.float32); cv2.fillConvexPoly(layer, poly.astype(np.int32), 1.0)
        shade *= 1 - strength * cv2.GaussianBlur(layer, (0, 0), blur)
    img = np.clip(img.astype(np.float32) * shade[..., None], 0, 255)

    # --- noise, blur, compression
    sigma, sp_amount, jpeg, blur_s = [(0, 0, 100, 0), (6, 0, 95, 0), (14, 0.01, 55, 0.8), (28, 0.03, 25, 1.4)][L["noise"]]
    if blur_s: img = cv2.GaussianBlur(img, (0, 0), blur_s)
    if sigma: img = img + rng.normal(0, sigma, img.shape)
    if sp_amount:
        r = rng.random((H, W)); img[r < sp_amount / 2] = 0; img[r > 1 - sp_amount / 2] = 255
    img = np.clip(img, 0, 255).astype(np.uint8)
    if jpeg < 100:
        ok, buf = cv2.imencode(".jpg", img, [cv2.IMWRITE_JPEG_QUALITY, jpeg]); img = cv2.imdecode(buf, cv2.IMREAD_COLOR)

    abc = line_abc((cx, cy), (cx + d[0], cy + d[1]))
    seg = clip_line_to_rect(abc, W, H)
    gt = dict(theta=fold_angle(theta), p1=seg[0], p2=seg[1], mid=((seg[0][0] + seg[1][0]) / 2, (seg[0][1] + seg[1][1]) / 2), abc=abc, levels=L, seed=seed)
    return img, gt


def _selftest():
    a, ga = make_wall_scene(5, levels=dict(noise=2, shadow=2)); b, gb = make_wall_scene(5, levels=dict(noise=2, shadow=2))
    assert a.shape == (360, 480, 3) and (a == b).all() and ga["theta"] == gb["theta"], "same seed must give the identical image"
    c, _ = make_wall_scene(6, levels=dict(noise=2, shadow=2)); assert not (a == c).all()
    for lv in range(4): make_wall_scene(lv, levels=dict(shadow=lv, noise=lv, broken=lv, distract=lv, angle=lv), style="unseen")      # every level runs
    assert -90 < ga["theta"] <= 90 and 0 <= ga["p1"][0] <= 480


if __name__ == "__main__":
    _selftest()
    print("OK:", "synthetic_data/wall_scenes.py")
