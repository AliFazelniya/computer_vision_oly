def _hsv_bgr(h, s=220, v=235):
    return tuple(int(x) for x in cv2.cvtColor(np.uint8([[[h, s, v]]]), cv2.COLOR_HSV2BGR)[0, 0])

def make_crossing_video(seed, n_frames=170, size=(240, 320), line=((30, 112), (290, 128)), n_objects=7, stress=None, margin_for_gt=4.0):
    """
    Synthetic video with exact ground truth.
    Returns frames (list of BGR uint8), gt_tracks (per frame {id: [x1,y1,x2,y2]}), gt_events (true crossings), meta.
    stress: dict(occlusion 0-3, fast 0-3, similar 0-3)
    """
    S = dict(occlusion=0, fast=0, similar=0); S.update(stress or {})
    rng = np.random.default_rng(seed); H, W = size
    A, B = np.array(line[0], float), np.array(line[1], float); d = (B - A) / np.linalg.norm(B - A); n = np.array([-d[1], d[0]])   # n: +u side
    speed_mult = [1.0, 2.5, 4.5, 7.0][S["fast"]]

    # ---- objects: a list of (normal-coordinate u) waypoints over time, plus a position s along the line
    objs = []
    for k in range(n_objects):
        w, h = rng.integers(18, 26), rng.integers(28, 40)
        hue = [int(rng.integers(0, 170))]                                                   # distinct colours by default
        if S["similar"] >= 2 or (S["similar"] == 1 and k % 2 == 0): hue = [20]               # similar: identical colour
        v = rng.uniform(1.6, 2.6) * speed_mult
        direction = (1 if k % 2 == 0 else -1) if S["similar"] >= 3 else (1 if rng.random() < .5 else -1)      # level 3: opposite directions
        t0 = int(rng.integers(0, 55)) if S["similar"] < 3 else int(rng.integers(0, 25))   # level 3: objects overlap in time
        # lanes: evenly spaced along the line so objects do NOT overlap by default; 'similar' compresses the lanes on purpose
        span = [0.92, 0.6, 0.42, 0.26][S["similar"]]
        s0 = (0.5 + ((k + 0.5) / n_objects - 0.5) * span + rng.uniform(-0.01, 0.01)) * np.linalg.norm(B - A)
        kind = "cross"
        if k == n_objects - 2: kind = "loiter"
        if k == n_objects - 1: kind = "back_forth"
        u_start, u_end = -direction * 75, direction * 75
        wp = [(t0, u_start)]; t = t0
        if kind == "cross":
            wp.append((t0 + abs(u_end - u_start) / v, u_end))
        elif kind == "loiter":
            t += abs(u_start) / v - 3; wp.append((t, u_start * 0.02))                       # arrives at the line...
            for j in range(10): t += 3; wp.append((t, (2.5 if j % 2 == 0 else -2.5)))         # ...and wobbles with amplitude 2.5 px (< margin)
            t += abs(u_end) / v; wp.append((t, u_end))                                       # then really crosses
        else:
            t += abs(u_start * 0.4 + 0) / v + 20 / v; wp.append((t, direction * 30)); t += 60 / v + 8; wp.append((t, -direction * 30))
            t += 45 / v; wp.append((t, -direction * 70))
        objs.append(dict(id=k + 1, w=int(w), h=int(h), color=_hsv_bgr(hue[0]), wp=wp, s0=float(s0), drift=float(rng.uniform(-0.08, 0.08) * speed_mult), t0=t0, kind=kind))

    # ---- occluders (grey pillars drawn on top of everything)
    occl = []
    L_ = np.linalg.norm(B - A)
    spots = {0: [], 1: [(0.35, 22, 85)], 2: [(0.5, 50, 100)], 3: [(0.3, 40, 100), (0.62, 55, 120)]}[S["occlusion"]]
    for frac, ow, oh in spots:
        c = A + d * frac * L_; occl.append((int(c[0] - ow / 2), int(c[1] - oh / 2), int(ow), int(oh)))

    bg = np.full((H, W, 3), 128, np.float32) + np.linspace(-18, 18, W, dtype=np.float32)[None, :, None] + cv2.resize(rng.normal(0, 6, (H // 12 + 2, W // 12 + 2)).astype(np.float32), (W, H))[..., None]
    frames, gt_tracks = [], []
    def pos(o, t):
        if t < o["wp"][0][0] or t > o["wp"][-1][0] + 1: return None
        ts, us = [p[0] for p in o["wp"]], [p[1] for p in o["wp"]]
        u = float(np.interp(t, ts, us)); s = o["s0"] + o["drift"] * (t - o["t0"])
        return A + d * s + n * u
    for t in range(n_frames):
        f = bg + rng.normal(0, 4, (H, W, 3)).astype(np.float32); f = np.clip(f, 0, 255).astype(np.uint8); gt = {}
        for o in objs:
            c = pos(o, t)
            if c is None: continue
            x1, y1, x2, y2 = c[0] - o["w"] / 2, c[1] - o["h"] / 2, c[0] + o["w"] / 2, c[1] + o["h"] / 2
            if x2 < 0 or y2 < 0 or x1 > W or y1 > H: continue
            gt[o["id"]] = [float(x1), float(y1), float(x2), float(y2)]
            xa, ya, xb, yb = max(0, int(round(x1))), max(0, int(round(y1))), min(W, int(round(x2))), min(H, int(round(y2)))
            f[ya:yb, xa:xb] = np.clip(np.array(o["color"], np.float32) + rng.normal(0, 8, (yb - ya, xb - xa, 3)), 0, 255).astype(np.uint8)
        for (ox, oy, ow, oh) in occl: cv2.rectangle(f, (ox, oy), (ox + ow, oy + oh), (110, 110, 110), -1)
        frames.append(f); gt_tracks.append(gt)

    gt_counter = LineCrossingCounter(line[0], line[1], margin=margin_for_gt, dedup=False)
    for t, gt in enumerate(gt_tracks): gt_counter.update(t, [(i, b) for i, b in gt.items()])
    return frames, gt_tracks, gt_counter.events, dict(line=line, occluders=occl, objects=objs, stress=S)


def _selftest():
    f1, g1, e1, m1 = make_crossing_video(3, n_frames=60); f2, g2, e2, m2 = make_crossing_video(3, n_frames=60)
