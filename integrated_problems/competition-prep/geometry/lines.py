import math
import cv2
import numpy as np


def fold_angle(a):
    """Fold an angle in degrees into (-90, 90]  (lines are undirected)."""
    a = (a + 90.0) % 180.0 - 90.0
    return 90.0 if a == -90.0 else a

def line_angle_deg(p1, p2):
    return fold_angle(math.degrees(math.atan2(p2[1] - p1[1], p2[0] - p1[0])))

def angle_diff_deg(a, b):
    """Smallest difference between two UNDIRECTED line angles, in [0, 90]."""
    d = abs(a - b) % 180.0
    return min(d, 180.0 - d)

def line_abc(p1, p2):
    """Line through two points as (a, b, c), a^2 + b^2 = 1:  a*x + b*y + c = 0  (signed distance in pixels)."""
    dx, dy = p2[0] - p1[0], p2[1] - p1[1]
    n = math.hypot(dx, dy)
    if n < 1e-9: raise ValueError("degenerate line: identical points")
    a, b = -dy / n, dx / n
    return a, b, -(a * p1[0] + b * p1[1])

def signed_distance(pt, abc):
    return abc[0] * pt[0] + abc[1] * pt[1] + abc[2]

def point_line_distance(pt, p1, p2):
    """Perpendicular distance from `pt` to the INFINITE line through p1, p2."""
    return abs(signed_distance(pt, line_abc(p1, p2)))

def clip_line_to_rect(abc, w, h):
    """Intersect an infinite line with the image rectangle -> two integer end points, or None if it misses the image."""
    a, b, c = abc
    x0, y0, dx, dy, far = -a * c, -b * c, b, -a, 2.0 * (w + h)
    p1 = (int(round(x0 - dx * far)), int(round(y0 - dy * far))); p2 = (int(round(x0 + dx * far)), int(round(y0 + dy * far)))
    ok, q1, q2 = cv2.clipLine((0, 0, w, h), p1, p2)
    return (q1, q2) if ok else None

def segments_intersect(p1, p2, q1, q2):
    """True if the closed segments p1p2 and q1q2 intersect (orientation test; handles collinear overlap)."""
    def orient(a, b, c):
        v = (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])
        return 0 if abs(v) < 1e-12 else (1 if v > 0 else -1)
    def on_seg(a, b, c):
        return min(a[0], b[0]) - 1e-12 <= c[0] <= max(a[0], b[0]) + 1e-12 and min(a[1], b[1]) - 1e-12 <= c[1] <= max(a[1], b[1]) + 1e-12
    o1, o2, o3, o4 = orient(p1, p2, q1), orient(p1, p2, q2), orient(q1, q2, p1), orient(q1, q2, p2)
    if o1 != o2 and o3 != o4: return True
    return (o1 == 0 and on_seg(p1, p2, q1)) or (o2 == 0 and on_seg(p1, p2, q2)) or (o3 == 0 and on_seg(q1, q2, p1)) or (o4 == 0 and on_seg(q1, q2, p2))

def fit_line_tls(points, weights=None):
    """Total-least-squares line fit (minimises PERPENDICULAR distances, unlike y = m x + b which fails for vertical lines).
    Returns (abc, centroid, direction_unit_vector)."""
    P = np.asarray(points, float)
    w = np.ones(len(P)) if weights is None else np.asarray(weights, float)
    c = (P * w[:, None]).sum(0) / w.sum()
    cov = ((P - c) * w[:, None]).T @ (P - c) / w.sum()
    vals, vecs = np.linalg.eigh(cov)
    d = vecs[:, 1]                                   # eigenvector of the LARGEST eigenvalue = line direction
    a, b = -d[1], d[0]
    return (float(a), float(b), float(-(a * c[0] + b * c[1]))), c, d


