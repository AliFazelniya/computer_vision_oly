import time


class Timer:
    """Context manager: `with Timer() as t: ...; t.ms`"""
    def __init__(self, label=""):
        self.label, self.elapsed = label, 0.0
    def __enter__(self):
        self._t0 = time.perf_counter(); return self
    def __exit__(self, *exc):
        self.elapsed = time.perf_counter() - self._t0
    @property
    def ms(self):
        return self.elapsed * 1000.0

class ContestClock:
    """A visible time budget. Call .start(), then .left() as often as you like."""
    def __init__(self, minutes=60): self.minutes, self.t0 = minutes, None
    def start(self): self.t0 = time.time(); print(f"Clock started: {self.minutes} minutes."); return self
    def left(self):
        if self.t0 is None: return float(self.minutes)
        return max(0.0, self.minutes - (time.time() - self.t0) / 60.0)
    def status(self): print(f"{self.left():.1f} min left" + ("  *** TIME IS UP ***" if self.left() <= 0 else ""))


