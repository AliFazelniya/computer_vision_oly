import logging


def get_logger(name="phase5", level=logging.INFO, logfile=None):
    """Console (+ optional file) logger that does not add duplicate handlers when a cell is re-run."""
    lg = logging.getLogger(name); lg.setLevel(level)
    if not lg.handlers:
        fmt = logging.Formatter("%(asctime)s | %(levelname)s | %(name)s | %(message)s", "%H:%M:%S")
        sh = logging.StreamHandler(); sh.setFormatter(fmt); lg.addHandler(sh)
        if logfile:
            fh = logging.FileHandler(logfile, encoding="utf-8"); fh.setFormatter(fmt); lg.addHandler(fh)
    return lg


