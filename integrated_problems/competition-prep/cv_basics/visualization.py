def show_grid(images, titles=None, cols=3, cell=(4.2, 3.2), save=None):
    """Show BGR / gray images in a grid (converts BGR->RGB for matplotlib)."""
    n = len(images); rows = max(1, math.ceil(n / cols))
    fig, axes = plt.subplots(rows, cols, figsize=(cell[0] * cols, cell[1] * rows))
    axes = np.atleast_1d(axes).flatten()
    for i, ax in enumerate(axes):
        ax.axis("off")
        if i < n:
            im = images[i]
            ax.imshow(cv2.cvtColor(im, cv2.COLOR_BGR2RGB) if im.ndim == 3 else im, cmap=None if im.ndim == 3 else "gray")
            if titles is not None: ax.set_title(str(titles[i]), fontsize=8)
    plt.tight_layout()
    if save: fig.savefig(save, dpi=100)
    plt.show()

def draw_tracking_frame(frame, tracks, line, counter=None):
    vis = frame.copy()
    cv2.line(vis, tuple(int(v) for v in line[0]), tuple(int(v) for v in line[1]), (0, 255, 255), 2, cv2.LINE_AA)
    for tid, box in tracks.items():
        col = tuple(int(c) for c in np.random.default_rng(tid * 7).integers(60, 255, 3))
        cv2.rectangle(vis, (int(box[0]), int(box[1])), (int(box[2]), int(box[3])), col, 2)
        cv2.putText(vis, f"#{tid}", (int(box[0]), int(box[1]) - 3), cv2.FONT_HERSHEY_SIMPLEX, 0.45, col, 1, cv2.LINE_AA)
    if counter is not None:
        c = counter.counts; cv2.putText(vis, f"+{c['pos']}  -{c['neg']}", (6, 18), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 255, 255), 2, cv2.LINE_AA)
    return vis


