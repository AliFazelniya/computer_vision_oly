    with tempfile.TemporaryDirectory() as d:
        d = Path(d); img = np.random.default_rng(0).integers(0, 255, (20, 30, 3), dtype=np.uint8); cv2.imwrite(str(d / "a.png"), img)
        assert load_image(d / "a.png").shape == (20, 30, 3) and load_image(d / "a.png", gray=True).ndim == 2
