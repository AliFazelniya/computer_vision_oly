        frames = [np.full((24, 32, 3), i * 20, np.uint8) for i in range(6)]
        v = write_video(frames, d / "v.mp4")
        assert sum(1 for _ in iter_frames(v)) == 6 and sum(1 for _ in iter_frames(v, stride=2)) == 3
        (d / "seq").mkdir()
        for i, f in enumerate(frames): cv2.imwrite(str(d / "seq" / f"{i:03d}.png"), f)       # image-sequence folders (MOT17 style)
        assert sum(1 for _ in iter_frames(d / "seq")) == 6


