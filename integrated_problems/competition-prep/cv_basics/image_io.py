import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))     # lets modules import their siblings when run as scripts
import cv2
import numpy as np


def load_image(path, gray=False):
    """cv2.imread silently returns None for a bad path: fail loudly instead. Returns BGR uint8 (or gray)."""
    img = cv2.imread(str(path), cv2.IMREAD_GRAYSCALE if gray else cv2.IMREAD_COLOR)
    if img is None:
        raise FileNotFoundError(f"Cannot read image: {path}")
    return img

def write_video(frames, path, fps=25):
    h, w = frames[0].shape[:2]; vw = cv2.VideoWriter(str(path), cv2.VideoWriter_fourcc(*"mp4v"), fps, (w, h))
    for f in frames: vw.write(f)
    vw.release(); return path

def iter_frames(source, stride=1, max_frames=None):
    """Yield BGR frames from a video file OR a folder of images (e.g. MOT17 .../img1/)."""
    src = Path(source); n = 0
    if src.is_dir():
        files = sorted(p for p in src.iterdir() if p.suffix.lower() in (".jpg", ".jpeg", ".png", ".bmp"))
        gen = (load_image(p) for p in files)
    else:
        cap = cv2.VideoCapture(str(src))
        if not cap.isOpened(): raise FileNotFoundError(f"Cannot open video {src}")
        def _g():
            while True:
                ok, fr = cap.read()
                if not ok: break
                yield fr
            cap.release()
        gen = _g()
    for i, fr in enumerate(gen):
        if i % stride: continue
        yield fr; n += 1
        if max_frames and n >= max_frames: break


